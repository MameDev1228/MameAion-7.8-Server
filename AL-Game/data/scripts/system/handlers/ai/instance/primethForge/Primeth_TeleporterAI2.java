@AIName("Primeth_Teleporter")
public class Primeth_TeleporterAI2 extends NpcAI2
{
	@Override
    protected void handleCreatureSee(Creature creature) {
        checkDistance(this, creature);
    }
	
    @Override
    protected void handleCreatureMoved(Creature creature) {
        checkDistance(this, creature);
    }
	
	private void checkDistance(NpcAI2 ai, Creature creature) {
		if (creature instanceof Player && !creature.getLifeStats().isAlreadyDead()) {
			final Player player = (Player) creature;
			if (MathUtil.isIn3dRange(getOwner(), creature, 8)) {
				player.setState(CreatureState.FLIGHT_TELEPORT);
				player.unsetState(CreatureState.ACTIVE);
				player.setFlightTeleportId(417001);
				PacketSendUtility.sendPacket(player, new SM_EMOTION(player, EmotionType.START_FLYTELEPORT, 417001, 0));
			}
		}
	}
	
	@Override
	public boolean isMoveSupported() {
		return false;
	}
}